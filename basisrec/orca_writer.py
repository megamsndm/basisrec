"""ORCA input file generator.

Produces a complete, copy-paste-ready ORCA input file with:
    - Standard ORCA keywords block (method, SCF settings, etc.)
    - Geometry block in Cartesian coordinates from the XYZ file
    - ``%basis ... end`` block with full Gaussian exponents and
      contraction coefficients fetched from the Basis Set Exchange.

Per-atom basis sets are handled via ORCA's ``newgto`` / ``addgto`` syntax:
    - ``newgto "El" ... end`` — sets the basis for an element globally.
    - When two atoms of the same element get different basis sets,
      the higher-quality one is set globally with ``newgto``, and the
      atom(s) needing the lower-quality basis get ``addgto`` overrides
      keyed by atom index.

This ensures the output is always valid ORCA syntax regardless of
how heterogeneous the per-atom recommendations are.
"""

from __future__ import annotations

import logging
from collections import defaultdict
from typing import Dict, List, Optional

from .basis_library import fetch_basis_block_orca
from .exceptions import ORCAWriterError
from .models import BasisRecommendation, Molecule

logger = logging.getLogger(__name__)

# Default ORCA method line — user can override
DEFAULT_METHOD = "! RKS B3LYP def2/J TightSCF Grid4 RIJCOSX"
DEFAULT_MAXCORE = 2000
DEFAULT_NPROCS = 4


def write_orca_input(
    molecule: Molecule,
    recommendations: List[BasisRecommendation],
    method_line: str = DEFAULT_METHOD,
    maxcore_mb: int = DEFAULT_MAXCORE,
    nprocs: int = DEFAULT_NPROCS,
    method_rec=None,
    output_path: Optional[str] = None,
) -> str:
    """Generate a complete ORCA input file string.

    Parameters
    ----------
    molecule:
        The parsed molecule (provides geometry and title).
    recommendations:
        Per-atom basis set recommendations from the decision engine.
    method_line:
        The ORCA ``!`` keywords line (method, convergence, grids).
    maxcore_mb:
        Memory per core in MB for the ``%maxcore`` directive.
    nprocs:
        Number of parallel processes for the ``%pal`` block.
    output_path:
        If provided, the generated input is also written to this file.

    Returns
    -------
    str
        Complete ORCA input file as a string.

    Raises
    ------
    ORCAWriterError
        If the basis block cannot be generated for any element.
    """
    sections = []

    sections.append(_header_comment(molecule, recommendations))
    if method_rec is not None:
        sections.append(method_rec.reasoning_block())
        sections.append("#")
    sections.append(method_line)
    sections.append("")
    sections.append(f"%maxcore {maxcore_mb}")
    sections.append(f"%pal nprocs {nprocs} end")
    sections.append("")
    if method_rec is not None:
        scf_block = method_rec.scf_block()
        if scf_block:
            sections.append(scf_block)
            sections.append("")
        solvent_block = method_rec.solvent_block()
        if solvent_block:
            sections.append(solvent_block)
            sections.append("")
    sections.append(_basis_block(molecule, recommendations))
    sections.append("")
    sections.append(_geometry_block(molecule))
    sections.append("")

    content = "\n".join(sections)

    if output_path:
        try:
            with open(output_path, "w", encoding="utf-8") as fh:
                fh.write(content)
            logger.info("ORCA input written to '%s'.", output_path)
        except OSError as exc:
            raise ORCAWriterError(f"Cannot write to '{output_path}': {exc}") from exc

    return content


def _header_comment(
    molecule: Molecule,
    recommendations: List[BasisRecommendation],
) -> str:
    """Generate the header comment block with full per-atom summary."""
    lines = [
        "# " + "=" * 60,
        "# Generated by BasisRec",
        f"# Molecule : {molecule.title or 'untitled'}",
        f"# Atoms    : {molecule.n_atoms}",
        "#",
        "# Per-atom basis set recommendations:",
        "# " + "-" * 56,
        f"# {'Idx':<5} {'Sym':<4} {'Basis':<20} {'Conf':<8} {'Source':<6}",
        "# " + "-" * 56,
    ]
    for rec in recommendations:
        lines.append(
            f"# {rec.atom_index:<5} {rec.symbol:<4} {rec.basis_name:<20} "
            f"{rec.confidence:<8.0%} {rec.source}"
        )
    lines.append("# " + "=" * 60)
    return "\n".join(lines)


def _basis_block(
    molecule: Molecule,
    recommendations: List[BasisRecommendation],
) -> str:
    """Build the ``%basis ... end`` block.

    Strategy:
        1. For each element, find all basis sets recommended across
           its atoms. If all atoms of that element get the same basis,
           use a single ``newgto`` block.
        2. If atoms of the same element get different bases, use
           ``newgto`` for the majority/best basis and ``addgto``
           with atom indices for the exceptions.
    """
    # Map: element → list of (atom_index, basis_name)
    by_element: Dict[str, List[tuple]] = defaultdict(list)
    for rec in recommendations:
        by_element[rec.symbol].append((rec.atom_index, rec.basis_name))

    lines = ["%basis"]

    for element, atom_basis_pairs in sorted(by_element.items()):
        basis_names = [b for _, b in atom_basis_pairs]
        unique_bases = set(basis_names)

        if len(unique_bases) == 1:
            # All atoms of this element share one basis — simple newgto
            basis_name = basis_names[0]
            lines.append("")
            lines.append(f'  # {element}: {basis_name}')
            lines.append(_newgto_block(element, basis_name))
        else:
            # Mixed: pick the highest-quality basis as the element default,
            # override the rest with addgto.
            default_basis = _pick_default_basis(basis_names)
            lines.append("")
            lines.append(f'  # {element}: mixed — default {default_basis}')
            lines.append(_newgto_block(element, default_basis))

            for atom_idx, basis_name in atom_basis_pairs:
                if basis_name != default_basis:
                    lines.append("")
                    lines.append(
                        f'  # Atom index {atom_idx + 1} ({element}): '
                        f'override to {basis_name}'
                    )
                    lines.append(_addgto_block(atom_idx + 1, element, basis_name))

    lines.append("")
    lines.append("end")
    return "\n".join(lines)


def _newgto_block(element: str, basis_name: str) -> str:
    """Return the ``newgto "El" ... end`` string for *element*."""
    try:
        basis_data = fetch_basis_block_orca(basis_name, element)
    except Exception as exc:
        raise ORCAWriterError(
            f"Cannot fetch basis '{basis_name}' for element '{element}': {exc}"
        ) from exc

    return f'  newgto "{element}"\n{_indent(basis_data, 4)}\n  end'


def _addgto_block(atom_number: int, element: str, basis_name: str) -> str:
    """Return the ``addgto N "El" ... end`` string for atom override.

    *atom_number* is 1-based as required by ORCA.
    """
    try:
        basis_data = fetch_basis_block_orca(basis_name, element)
    except Exception as exc:
        raise ORCAWriterError(
            f"Cannot fetch basis '{basis_name}' for element '{element}': {exc}"
        ) from exc

    return f'  addgto {atom_number} "{element}"\n{_indent(basis_data, 4)}\n  end'


def _geometry_block(molecule: Molecule) -> str:
    """Return the ``* xyz charge multiplicity ... *`` block."""
    lines = [f"* xyz {molecule.charge} {molecule.multiplicity}"]
    for atom in molecule.atoms:
        lines.append(
            f"  {atom.symbol:<3}  {atom.x:12.6f}  {atom.y:12.6f}  {atom.z:12.6f}"
        )
    lines.append("*")
    return "\n".join(lines)


def _indent(text: str, spaces: int) -> str:
    """Indent every line of *text* by *spaces* spaces."""
    pad = " " * spaces
    return "\n".join(pad + line for line in text.splitlines())


def _pick_default_basis(basis_names: List[str]) -> str:
    """Return the highest-quality basis from a list of names."""
    from .basis_library import _TIER_ORDER_MAP, get_tier
    return max(basis_names, key=lambda b: _TIER_ORDER_MAP.get(get_tier(b), 0))
